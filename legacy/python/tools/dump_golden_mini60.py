#!/usr/bin/env python3
"""Dump protocol_mini60 frames as golden fixtures for the Rust port.

Every frame the Rust `aether-proto` crate builds is compared byte-for-byte
against this output, so the Rust port can never drift from the Python
reference (itself golden-tested against vendor captures and hardware-verified
on the F75 HE).

    python tools/dump_golden_mini60.py ../../crates/aether-proto/tests/golden/mini60.json
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

import protocol_mini60 as pm                       # noqa: E402
from drivers.mini60 import build_stream_frames, build_stream_clear   # noqa: E402

FL = 64


def hexf(frame):
    return bytes(int(b) & 0xFF for b in frame).hex()


def records_to_frames(records):
    """The Mini60Driver._write_actuation_records paging, without a device."""
    offs = pm.act_page_offsets(FL)
    per = pm.act_records_per_frame(FL)
    out = []
    for off in offs:
        start = off // pm.ACT_RECORD_SIZE
        recs = records[start:start + per]
        out.append(hexf(pm.build_actuation_frame(off, recs, final=(off == offs[-1]), frame_len=FL)))
    return out


def main(path):
    empty = [None] * 126
    w_fixed = list(empty)
    w_fixed[34] = (0, 1.50, 0.0, 0.0, 0)
    w_rt = list(empty)
    w_rt[34] = (1, 1.50, 0.30, 0.30, 0)
    mixed = list(empty)
    for i, (flags, trip, p, r, axis) in {
        0: (0, 2.00, 0.0, 0.0, 0), 17: (1, 0.31, 0.15, 0.20, 0),
        83: (1, 3.00, 1.25, 0.75, 0), 107: (0, 0.10, 0.0, 0.0, 3),
        125: (3, 3.40, 3.40, 0.01, 0)}.items():
        mixed[i] = (flags, trip, p, r, axis)

    stream_colors = [((i * 7) & 0xFF, (255 - i) & 0xFF, (i * 3 + 1) & 0xFF) for i in range(126)]
    led_table = pm.build_custom_led_table(stream_colors)

    # one of every advanced record type, over an otherwise empty table
    keys = [0] * pm.KEY_TABLE_SIZE
    keys = pm.apply_key_record(keys, 0, pm.key_record_remap(0x29))
    keys = pm.apply_key_record(keys, 12, pm.key_record_tgl())
    keys = pm.apply_key_record(keys, 34, pm.key_record_dks(0))
    keys = pm.apply_key_record(keys, 48, pm.key_record_mt(25, 0x39, 0xE0))
    keys = pm.apply_paired_key_record(keys, 49, 51, pm.key_record_socd(0x04, 0x07, 3))
    keys = pm.apply_paired_key_record(keys, 33, 35, pm.key_record_rs(0x14, 0x08))
    dks = pm.build_dks_table({0: pm.dks_slot_record([1.6, 3.0, 3.0, 1.6], [0x1A], [1, 1, 1, 1])})

    gold = {
        "_comment": "Generated by legacy/python/tools/dump_golden_mini60.py from protocol_mini60.py. Do not edit.",
        "device_info": [hexf(f) for f in pm.build_device_info_frames(FL)],
        "light_read": hexf(pm.build_light_read(FL)),
        "actuation_reads": [hexf(f) for f in pm.iter_actuation_reads(FL)],
        "config_reads": [hexf(f) for f in pm.build_config_read_frames(FL)],
        "key_table_reads": [hexf(f) for f in pm.build_key_table_read_frames(FL)],
        "custom_led_reads": [hexf(f) for f in pm.build_custom_led_read_frames(FL)],
        "light_writes": [
            {"args": {"mode": m, "r": r, "g": g, "b": b, "alpha": a, "color_mode": cm,
                      "brightness": br, "speed": sp},
             "frame": hexf(pm.build_light(m, r, g, b, brightness=br, speed=sp, alpha=a,
                                          color_mode=cm, frame_len=FL))}
            for (m, r, g, b, a, cm, br, sp) in [
                (1, 255, 0, 0, 255, 0, 5, 3), (11, 255, 255, 255, 0, 1, 5, 3),
                (20, 0x90, 0xEE, 0x90, 255, 1, 5, 5), (8, 1, 2, 3, 255, 1, 0, 0)]],
        "actuation_writes": {
            "empty": records_to_frames(empty),
            "w_fixed_1_50": records_to_frames(w_fixed),
            "w_rt_1_50_0_30": records_to_frames(w_rt),
            "mixed": records_to_frames(mixed),
        },
        "actuation_mixed_records": {str(i): list(r) for i, r in enumerate(mixed) if r},
        "stream_colors": [list(c) for c in stream_colors],
        "stream_frames": [hexf(f) for f in build_stream_frames(led_table, FL)],
        "custom_led_writes": [hexf(f) for f in pm.build_custom_led_write_frames(led_table, FL)],
        "key_table_writes": [hexf(f) for f in pm.build_key_table_write_frames(keys, FL)],
        "dks_reads": [hexf(f) for f in pm.build_dks_travel_read_frames(FL)],
        "dks_writes": [hexf(f) for f in pm.build_dks_travel_write_frames(dks, FL)],
        "stream_clear": hexf(build_stream_clear(FL)),
        "dangerous_cmds": sorted(pm.DANGEROUS_CMDS),
    }
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(gold, f, indent=1)
        f.write("\n")
    print("wrote", path)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "mini60_golden.json")
